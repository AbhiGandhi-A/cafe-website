export const getItemById = (id: string) => menuItems.find((i) => i.id === id);
export const getItemCountByCategory = (categoryId: string) => {
  const cat = categories.find((c) => c.id === categoryId);
  if (!cat) return 0;
  return menuItems.filter((i) => i.category === cat.name).length;
};
export const getCategoryName = (categoryId: string) => {
  const cat = categories.find((c) => c.id === categoryId);
  return cat ? cat.name : "";
};
export const getCategoryLabel = (categoryId: string) => {
  if (categoryId === "all") return "ALL";
  return getCategoryName(categoryId).toUpperCase();
};
export const getItemsByCategory = (categoryId: string): MenuItem[] => {
  if (categoryId === "all") return menuItems;
  const cat = categories.find((c) => c.id === categoryId);
  if (!cat) return menuItems;
  return menuItems.filter((i) => i.category === cat.name);
};

export const popularItems: MenuItem[] = menuItems.filter((i) => i.popular);
